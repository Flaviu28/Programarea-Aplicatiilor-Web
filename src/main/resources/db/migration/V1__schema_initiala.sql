CREATE TABLE categorie (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nume VARCHAR(100) NOT NULL UNIQUE,
    descriere VARCHAR(500)
);

CREATE TABLE produs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nume VARCHAR(150) NOT NULL,
    descriere VARCHAR(1000),
    pret NUMERIC(10, 2) NOT NULL CHECK (pret >= 0),
    stoc INTEGER NOT NULL DEFAULT 0 CHECK (stoc >= 0),
    categorie_id BIGINT NOT NULL REFERENCES categorie (id),
    creat_la TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_produs_categorie ON produs (categorie_id);
